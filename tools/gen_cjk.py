#!/usr/bin/env python3
"""Generate a 16x16 4bpp CJK bitmap font for HYWOS.

Charset: GB2312 level-1 and level-2 hanzi (6763) plus common CJK punctuation and a few
symbols used by the UI. Glyphs are sorted by code point for binary search.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/wqy-microhei/wqy-microhei.ttc"
CELL_W = 16
CELL_H = 16
EXTRA = "，。！？：；、（）《》“”‘’—…·℃℉×÷￥"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "cjk.rs")


def hanzi_level1():
    out = set()
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except Exception:
                continue
            out.add(ch)
    return out


def main():
    chars = sorted(hanzi_level1() | set(EXTRA))
    font = ImageFont.truetype(FONT, 16)
    bits = []
    cps = []
    for ch in chars:
        img = Image.new("L", (CELL_W, CELL_H), 0)
        d = ImageDraw.Draw(img)
        d.text((0, -2), ch, font=font, fill=255)
        for y in range(CELL_H):
            for x in range(0, CELL_W, 2):
                hi = img.getpixel((x, y)) >> 4
                lo = img.getpixel((x + 1, y)) >> 4
                bits.append((hi << 4) | lo)
        cps.append(ord(ch))
    n = len(cps)
    per = CELL_W // 2 * CELL_H
    assert len(bits) == n * per
    lines = []
    for i in range(0, len(bits), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in bits[i:i + 24]) + ",")
    cp_lines = []
    for i in range(0, len(cps), 12):
        cp_lines.append("    " + ", ".join("0x%04x" % c for c in cps[i:i + 12]) + ",")
    text = (
        "// Generated by tools/gen_cjk.py - do not edit.\n"
        "pub const CJK_W: usize = %d;\n"
        "pub const CJK_H: usize = %d;\n"
        "pub const CJK_BPG: usize = %d;\n"
        "pub const CJK_COUNT: usize = %d;\n"
        "pub static CJK_CP: [u32; %d] = [\n%s\n];\n"
        "pub static CJK_BITS: [u8; %d] = [\n%s\n];\n"
    ) % (CELL_W, CELL_H, per, n, n, "\n".join(cp_lines), len(bits), "\n".join(lines))
    with open(OUT, "w") as fh:
        fh.write(text)
    print("glyphs=%d bytes=%d file=%d" % (n, len(bits), len(text)))


if __name__ == "__main__":
    main()