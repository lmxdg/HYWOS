#!/usr/bin/env python3
"""Generate 4-bit-per-pixel grayscale bitmap fonts for HYWOS.

Two faces are produced:
  FONT_8x16  - UI body text (96 glyphs, ASCII 32..127)
  FONT_16x32 - headings / boot logo

Glyph storage: 4bpp nibbles, two pixels per byte, rows are packed left to
right, top to bottom.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_CANDIDATES = [
    "/usr/share/fonts/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/dejavu/DejaVuSansMono-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
]

FIRST = 32
LAST = 126
COUNT = LAST - FIRST + 1


def find_font():
    for c in FONT_CANDIDATES:
        if os.path.exists(c):
            return c
    sys.exit("no TrueType font found")


def render(cell_w, cell_h, px_size, font_path, y_off):
    font = ImageFont.truetype(font_path, px_size)
    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new("L", (cell_w, cell_h), 0)
        d = ImageDraw.Draw(img)
        d.text((0, y_off), ch, font=font, fill=255)
        for y in range(cell_h):
            for x in range(0, cell_w, 2):
                hi = img.getpixel((x, y)) >> 4
                lo = img.getpixel((x + 1, y)) >> 4 if x + 1 < cell_w else 0
                out.append((hi << 4) | lo)
    return out


def emit(name, w, h, data):
    per = w // 2
    total = per * h
    lines = []
    for i in range(0, len(data), 24):
        chunk = data[i:i + 24]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    body = "\n".join(lines)
    return (
        "/// %dx%d 4bpp font, %d glyphs (ASCII 32..126), %d bytes/glyph\n"
        "pub static %s: [u8; %d] = [\n%s\n];\n\n"
        "pub const %s_W: usize = %d;\n"
        "pub const %s_H: usize = %d;\n"
        "pub const %s_BPG: usize = %d;\n"
    ) % (w, h, COUNT, total, name, len(data), body,
         name, w, name, h, name, total)


def main():
    src = os.path.join(os.path.dirname(__file__), "..", "src", "font.rs")
    f = find_font()
    small = render(8, 16, 15, f, -1)
    big = render(16, 32, 30, f, -3)
    text = "// Generated by tools/gen_font.py - do not edit by hand.\n\n"
    text += emit("FONT_8X16", 8, 16, small)
    text += emit("FONT_16X32", 16, 32, big)
    with open(src, "w") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (src, len(text)))


if __name__ == "__main__":
    main()