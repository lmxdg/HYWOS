#!/usr/bin/env python3
"""Convert the HYWOS logo into an RGBA array for the About page."""
import os
from PIL import Image

SRC = os.path.join(os.path.dirname(__file__), "..", "assets", "logo.png")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "logo.rs")
SIZE = 128


def main():
    img = Image.open(SRC).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    px = list(img.getdata())
    lines = []
    flat = []
    for r, g, b, a in px:
        flat.extend((r, g, b, a))
    for i in range(0, len(flat), 24):
        lines.append("    " + ", ".join(str(v) for v in flat[i:i + 24]) + ",")
    text = (
        "// Generated by tools/gen_logo_data.py - do not edit.\n"
        "pub const LOGO_SIZE: usize = %d;\n"
        "pub static LOGO_RGBA: [u8; %d] = [\n%s\n];\n"
    ) % (SIZE, len(flat), "\n".join(lines))
    with open(OUT, "w") as fh:
        fh.write(text)
    print("logo %dx%d -> %s (%d bytes)" % (SIZE, SIZE, OUT, len(text)))


if __name__ == "__main__":
    main()